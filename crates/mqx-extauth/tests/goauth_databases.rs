fn redis_command(port: u16, args: &[&str]) {
    run(
        tool("usr/bin/redis-cli")
            .args(["-e", "-c", "-h", HOST, "-p", &port.to_string()])
            .args(args),
        None,
    );
}

fn redis_server(port: u16, cluster: bool) -> Process {
    let dir = temp();
    let mut command = if cluster {
        Command::new(path("MOSQUITTO_GO_AUTH_REDIS_CLUSTER_SERVER"))
    } else {
        tool("usr/bin/redis-server")
    };
    command
        .args([
            "--bind",
            HOST,
            "--port",
            &port.to_string(),
            "--save",
            "",
            "--appendonly",
            "no",
            "--dir",
        ])
        .arg(dir.path());
    if cluster {
        command.args([
            "--cluster-enabled",
            "yes",
            "--cluster-config-file",
            "nodes.conf",
            "--cluster-node-timeout",
            "1000",
        ]);
    }
    Process::start(dir, &mut command, port)
}

fn cluster_ports() -> [u16; 3] {
    // Redis 6.2's cluster bus listens at the client port + 10000.
    let mut listeners = Vec::with_capacity(3);
    while listeners.len() < 3 {
        let client = TcpListener::bind((HOST, 0)).unwrap();
        let port = client.local_addr().unwrap().port();
        if let Some(bus) = port.checked_add(10000)
            && let Ok(bus) = TcpListener::bind((HOST, bus))
        {
            listeners.push((client, bus, port));
        }
    }
    std::array::from_fn(|index| listeners[index].2)
}

fn redis_seed(port: u16, db: &str) {
    for args in [
        &["SET", USER, HASH][..],
        &["SET", "admin", HASH],
        &["SET", "admin:su", "true"],
        &["SADD", "al'ice:sacls", "user/#"],
        &["SADD", "common:sacls", "common/%c/%u"],
        &["SADD", "al'ice:racls", "read/#"],
        &["SADD", "al'ice:wacls", "write/#"],
        &["SADD", "al'ice:rwacls", "rw/#"],
        &["LPUSH", "broken", "not a hash"],
    ] {
        let mut command = vec!["-n", db];
        command.extend_from_slice(args);
        redis_command(port, &command);
    }
}

#[tokio::test]
#[ignore = "requires sourced standalone and clustered Redis and go-auth reference environment"]
async fn redis() {
    let standalone = port();
    let _server = redis_server(standalone, false);
    let mut opts = options(
        "redis",
        &[
            ("redis_host", HOST),
            ("redis_port", &standalone.to_string()),
        ],
    );
    redis_seed(standalone, "1");
    let cases = [
        ("user/x", Verdict::Allow),
        ("common/dbal'ice/al'ice", Verdict::Allow),
        ("rw/x", Verdict::Deny),
    ];
    let mut checks = auth(USER).to_vec();
    checks.push(("broken", PASSWORD, Verdict::Error));
    parity(&opts, &checks, &cases).await;
    parity(
        &opts,
        &[("admin", PASSWORD, Verdict::Allow)],
        &[("elsewhere", Verdict::Allow)],
    )
    .await;
    let native = load(Library::GoAuth, opts.clone(), false).await.unwrap();
    let identity = native
        .acl_identity(Subject {
            client_id: "dbtest",
            username: Some(USER),
            binding: Binding::default(),
        })
        .unwrap();
    for (topic, access, want) in [
        ("rw/x", AclAccess::Write, Verdict::Allow),
        ("rw/x", AclAccess::Read, Verdict::Allow),
        ("read/x", AclAccess::Write, Verdict::Deny),
        ("", AclAccess::Read, Verdict::Allow),
    ] {
        assert_eq!(
            native.authorize(&identity, topic, access).await.verdict,
            want
        );
    }
    native.halt().await;

    let ports = cluster_ports();
    let _nodes = ports.map(|port| redis_server(port, true));
    let addresses = ports.map(|port| format!("{HOST}:{port}"));
    run(
        tool("usr/bin/redis-cli")
            .args(["--cluster", "create"])
            .args(&addresses)
            .arg("--cluster-yes"),
        None,
    );
    let deadline = Instant::now() + Duration::from_secs(10);
    for port in ports {
        loop {
            let info = tool("usr/bin/redis-cli")
                .args(["-e", "-h", HOST, "-p", &port.to_string(), "CLUSTER", "INFO"])
                .output()
                .unwrap();
            if info.stdout.starts_with(b"cluster_state:ok") {
                break;
            }
            assert!(
                Instant::now() < deadline,
                "Redis Cluster did not converge: {}",
                String::from_utf8_lossy(&info.stdout)
            );
            thread::sleep(Duration::from_millis(30));
        }
    }
    redis_seed(ports[0], "0");
    opts.extend([
        (String::from("redis_mode"), String::from("cluster")),
        (
            String::from("redis_cluster_addresses"),
            addresses.join(", "),
        ),
    ]);
    parity(&opts, &checks, &cases).await;
}
