const JWT_SECRET: &str = "db-test-secret";

fn token(user: &str) -> String {
    let header = URL_SAFE_NO_PAD.encode(br#"{"alg":"HS256","typ":"JWT"}"#);
    let payload = URL_SAFE_NO_PAD.encode(serde_json::json!({ "sub": user }).to_string());
    let data = format!("{header}.{payload}");
    let mut hmac = Hmac::<Sha256>::new_from_slice(JWT_SECRET.as_bytes()).unwrap();
    hmac.update(data.as_bytes());
    let signature = URL_SAFE_NO_PAD.encode(hmac.finalize().into_bytes());
    format!("{data}.{signature}")
}

async fn jwt_local(db_opts: &Options, prefix: &str, query: &str) {
    let mut opts = options(
        "jwt",
        &[
            ("jwt_mode", "local"),
            ("jwt_db", prefix),
            ("jwt_secret", JWT_SECRET),
            ("jwt_userquery", query),
        ],
    );
    opts.extend(
        db_opts
            .iter()
            .filter(|(key, _)| key.starts_with(prefix))
            .map(|(key, value)| (format!("jwt_{key}"), value.clone())),
    );
    parity(
        &opts,
        &[
            (&token(USER), "ignored", Verdict::Allow),
            (&token("missing"), "ignored", Verdict::Error),
        ],
        &[
            ("units/dbal'ice/al'ice", Verdict::Allow),
            ("elsewhere", Verdict::Deny),
        ],
    )
    .await;
}

