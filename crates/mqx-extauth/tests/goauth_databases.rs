type Options = Vec<(String, String)>;

fn path(variable: &str) -> PathBuf {
    env::var_os(variable)
        .filter(|value| !value.is_empty())
        .map(PathBuf::from)
        .unwrap_or_else(|| panic!("set {variable} before running go-auth database reference tests"))
}

fn tool(relative: &str) -> Command {
    Command::new(path("MOSQUITTO_AUTH_PLUG_ROOT").join(relative))
}

fn temp() -> TempDir {
    tempfile::tempdir_in(path("TMPDIR")).unwrap()
}

fn port() -> u16 {
    TcpListener::bind((HOST, 0))
        .unwrap()
        .local_addr()
        .unwrap()
        .port()
}

fn run(command: &mut Command, input: Option<&str>) {
    if input.is_some() {
        command.stdin(Stdio::piped());
    }
    let mut child = command
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .unwrap_or_else(|error| panic!("spawn {:?}: {error}", command.get_program()));
    if let Some(input) = input {
        child
            .stdin
            .take()
            .unwrap()
            .write_all(input.as_bytes())
            .unwrap();
    }
    let out = child.wait_with_output().unwrap();
    assert!(
        out.status.success(),
        "{command:?}: {}\n{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
}

struct Process {
    child: Child,
    dir: TempDir,
}

impl Process {
    fn start(dir: TempDir, command: &mut Command, port: u16) -> Self {
        let log = fs::File::create(dir.path().join("service.log")).unwrap();
        let child = command
            .stdout(log.try_clone().unwrap())
            .stderr(log)
            .spawn()
            .unwrap_or_else(|error| panic!("spawn {:?}: {error}", command.get_program()));
        let mut process = Self { child, dir };
        let deadline = Instant::now() + Duration::from_secs(20);
        loop {
            assert!(
                process.child.try_wait().unwrap().is_none(),
                "{command:?}: {}",
                process.log()
            );
            if TcpStream::connect((HOST, port)).is_ok() {
                return process;
            }
            assert!(
                Instant::now() < deadline,
                "{command:?} did not start: {}",
                process.log()
            );
            thread::sleep(Duration::from_millis(30));
        }
    }

    fn log(&self) -> String {
        fs::read_to_string(self.dir.path().join("service.log")).unwrap_or_default()
    }
}

impl Drop for Process {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
}

fn options(backend: &str, entries: &[(&str, &str)]) -> Options {
    [
        ("backends", backend),
        ("auth_plugin_deny_special_chars", "false"),
    ]
    .into_iter()
    .chain(entries.iter().copied())
    .map(|(key, value)| (key.to_owned(), value.to_owned()))
    .collect()
}

fn reference(opts: &Options) -> (Process, u16) {
    let build = path("MOSQUITTO_BUILD_DIR");
    let plugin = path("MOSQUITTO_GO_AUTH_SO");
    let dir = temp();
    let port = port();
    let conf = dir.path().join("mosquitto.conf");
    let mut config = format!(
        "listener {port} {HOST}\nallow_anonymous false\nauth_plugin {}\nauth_plugin_deny_special_chars false\n",
        plugin.display()
    );
    for (name, value) in opts {
        if name == "auth_plugin_deny_special_chars" {
            continue;
        }
        config.push_str(&format!("auth_opt_{name} {value}\n"));
    }
    fs::write(&conf, config).unwrap();
    let process = Process::start(
        dir,
        Command::new(build.join("src/mosquitto"))
            .arg("-c")
            .arg(conf),
        port,
    );
    (process, port)
}

fn text(packet: &mut Vec<u8>, value: &str) {
    packet.extend_from_slice(&u16::try_from(value.len()).unwrap().to_be_bytes());
    packet.extend_from_slice(value.as_bytes());
}

fn send(socket: &mut TcpStream, ty: u8, payload: &[u8]) {
    let mut remaining = payload.len();
    let mut frame = Vec::with_capacity(payload.len() + 5);
    frame.push(ty);
    loop {
        let byte = (remaining % 128) as u8;
        remaining /= 128;
        frame.push(if remaining == 0 { byte } else { byte | 128 });
        if remaining == 0 {
            break;
        }
    }
    frame.extend_from_slice(payload);
    socket.write_all(&frame).unwrap();
}

fn receive(socket: &mut TcpStream) -> Option<(u8, Vec<u8>)> {
    let mut byte = [0u8];
    if let Err(err) = socket.read_exact(&mut byte) {
        assert_eq!(err.kind(), std::io::ErrorKind::UnexpectedEof);
        return None;
    }
    let packet = byte[0];
    let mut len = 0;
    for shift in [0, 7, 14, 21] {
        socket.read_exact(&mut byte).unwrap();
        len |= usize::from(byte[0] & 127) << shift;
        if byte[0] & 128 == 0 {
            break;
        }
    }
    let mut payload = vec![0; len];
    socket.read_exact(&mut payload).unwrap();
    Some((packet, payload))
}

fn connect(port: u16, client_id: &str, user: &str, password: &str) -> (Verdict, TcpStream) {
    let mut socket = TcpStream::connect((HOST, port)).unwrap();
    socket
        .set_read_timeout(Some(Duration::from_secs(5)))
        .unwrap();
    let mut packet = b"\x00\x04MQTT\x05\xc2\x00\x0a\x00".to_vec();
    for value in [client_id, user, password] {
        text(&mut packet, value);
    }
    send(&mut socket, 0x10, &packet);
    let verdict = match receive(&mut socket) {
        Some((0x20, data)) if data[1] == 0 => Verdict::Allow,
        Some((0x20, data)) if data[1] == 0x87 => Verdict::Deny,
        Some((0x20, data)) if data[1] == 0x80 => Verdict::Error,
        None => Verdict::Error,
        unexpected => panic!("unexpected CONNACK {unexpected:?}"),
    };
    (verdict, socket)
}

fn subscribe(socket: &mut TcpStream, id: u16, filter: &str) -> Verdict {
    let mut packet = id.to_be_bytes().to_vec();
    packet.push(0);
    text(&mut packet, filter);
    packet.push(0);
    send(socket, 0x82, &packet);
    match receive(socket) {
        Some((0x90, data)) if data[..2] == id.to_be_bytes() && data.last() == Some(&0) => {
            Verdict::Allow
        }
        Some((0x90, data)) if data[..2] == id.to_be_bytes() && data.last() == Some(&0x87) => {
            Verdict::Deny
        }
        Some((0x90, data)) if data[..2] == id.to_be_bytes() && data.last() == Some(&0x80) => {
            Verdict::Error
        }
        Some((0xe0, data)) if data.first() == Some(&0x80) => Verdict::Error,
        None => Verdict::Error,
        unexpected => panic!("unexpected SUBACK {unexpected:?}"),
    }
}

async fn parity(opts: &Options, auth: &[(&str, &str, Verdict)], acl: &[(&str, Verdict)]) {
    let native = load(Library::GoAuth, opts.clone(), false).await.unwrap();
    let (reference, port) = reference(opts);
    for (username, password, want) in auth.iter().copied() {
        // Username expansion uses a normal ID; expansion of a %u inserted
        // by substituting the client ID is checked in the SQL/Redis fixtures.
        let client_id = "db%u";
        let actual = native
            .authenticate(client_id, Some(username), Some(password.as_bytes()))
            .await;
        let (wire, mut socket) = connect(port, client_id, username, password);
        assert_eq!(actual, want, "native CONNECT as {username:?}");
        assert_eq!(
            wire,
            actual,
            "reference CONNECT as {username:?}: {}",
            reference.log()
        );
        if wire == Verdict::Allow {
            let subject = native
                .acl_identity(Subject {
                    client_id,
                    username: Some(username),
                    binding: Binding {
                        credentials: true,
                        ..Binding::default()
                    },
                })
                .unwrap();
            for (i, (topic, want)) in acl.iter().copied().enumerate() {
                let actual = native
                    .authorize(&subject, topic, AclAccess::Subscribe)
                    .await
                    .verdict;
                let wire = subscribe(&mut socket, u16::try_from(i + 1).unwrap(), topic);
                assert_eq!(actual, want, "native SUBSCRIBE {topic:?}");
                assert_eq!(
                    wire,
                    actual,
                    "reference SUBSCRIBE {topic:?}: {}",
                    reference.log()
                );
                if wire == Verdict::Error {
                    break;
                }
            }
        }
    }
    native.halt().await;
}

fn auth(user: &str) -> [(&str, &str, Verdict); 3] {
    [
        (user, PASSWORD, Verdict::Allow),
        (user, "wrong", Verdict::Deny),
        ("missing", PASSWORD, Verdict::Deny),
    ]
}

#[tokio::test]
#[ignore = "requires sourced go-auth and Mosquitto 2.1.4 reference environment"]
async fn sqlite() {
    let dir = temp();
    let file = dir.path().join("users.db");
    let db = rusqlite::Connection::open(&file).unwrap();
    seed_sqlite(&db);
    let mut opts = options(
        "sqlite",
        &[
            ("sqlite_source", file.to_str().unwrap()),
            (
                "sqlite_userquery",
                "SELECT hash FROM users WHERE name = ? ORDER BY rowid",
            ),
            (
                "sqlite_superquery",
                "SELECT admin FROM users WHERE name = ? ORDER BY rowid",
            ),
            (
                "sqlite_aclquery",
                "SELECT topic FROM acl WHERE name = ? AND acc = ? ORDER BY rowid",
            ),
        ],
    );
    let mut checks = auth(USER).to_vec();
    checks.push(("null", PASSWORD, Verdict::Deny));
    parity(
        &opts,
        &checks,
        &[
            ("units/dbal'ice/al'ice", Verdict::Allow),
            ("write", Verdict::Deny),
            ("elsewhere", Verdict::Deny),
        ],
    )
    .await;
    parity(
        &opts,
        &[("admin", PASSWORD, Verdict::Allow)],
        &[("anywhere", Verdict::Allow)],
    )
    .await;
    db.execute("INSERT INTO acl VALUES (?1, NULL, 4)", [USER])
        .unwrap();
    parity(
        &opts,
        &[(USER, PASSWORD, Verdict::Allow)],
        &[("units/dbal'ice/al'ice", Verdict::Error)],
    )
    .await;
    opts.iter_mut()
        .find(|(key, _)| key == "sqlite_userquery")
        .unwrap()
        .1 = "SELECT missing FROM users WHERE name = ?".into();
    parity(&opts, &[(USER, PASSWORD, Verdict::Error)], &[]).await;
    let memory = options(
        "sqlite",
        &[
            ("sqlite_source", "memory"),
            ("sqlite_userquery", "SELECT 'invalid' WHERE ? IS NULL"),
        ],
    );
    parity(&memory, &[(USER, PASSWORD, Verdict::Deny)], &[]).await;
}

fn seed_sqlite(db: &rusqlite::Connection) {
    db.execute_batch("CREATE TABLE users (name text, hash text, admin integer); CREATE TABLE acl (name text, topic text, acc integer);").unwrap();
    db.execute("INSERT INTO users VALUES (?1, ?2, 0), (?1, 'wrong-hash', 0), ('admin', ?2, 1), ('null', NULL, NULL)", (USER, HASH)).unwrap();
    db.execute(
        "INSERT INTO acl VALUES (?1, 'units/%c/%u', 4), (?1, 'write', 2)",
        [USER],
    )
    .unwrap();
}

fn sql_seed() -> String {
    format!(
        "CREATE TABLE users (name varchar(80), hash varchar(180), admin integer);\nINSERT INTO users VALUES ('al''ice', '{HASH}', 0), ('admin', '{HASH}', 1), ('null', NULL, NULL);\nCREATE TABLE acl (name varchar(80), topic varchar(100), acc integer);\nINSERT INTO acl VALUES ('al''ice', 'units/%c/%u', 4), ('al''ice', 'write', 2);\n"
    )
}

fn postgres_server() -> (Process, u16) {
    let bin = path("MOSQUITTO_AUTH_PLUG_POSTGRES");
    let dir = temp();
    let data = dir.path().join("data");
    let port = port();
    run(
        Command::new(bin.join("initdb"))
            .args([
                "--no-sync",
                "--no-locale",
                "--encoding=UTF8",
                "--auth=trust",
                "--username=mqtt",
                "-D",
            ])
            .arg(&data),
        None,
    );
    // The certificate identifies localhost, not the loopback IP. This lets
    // the fixture distinguish verify-ca from verify-full on IP connections.
    let cert = dir.path().join("server.crt");
    let key = dir.path().join("server.key");
    run(
        Command::new("openssl")
            .args([
                "req",
                "-x509",
                "-nodes",
                "-newkey",
                "rsa:2048",
                "-days",
                "1",
                "-subj",
                "/CN=localhost",
                "-addext",
                "subjectAltName=DNS:localhost",
                "-addext",
                "basicConstraints=critical,CA:FALSE",
                "-keyout",
            ])
            .arg(&key)
            .arg("-out")
            .arg(&cert),
        None,
    );
    let mut command = Command::new(bin.join("postgres"));
    command
        .arg("-D")
        .arg(data)
        .args(["-h", HOST, "-p", &port.to_string(), "-k"])
        .arg(dir.path())
        .args(["-c", "ssl=on", "-c"])
        .arg(format!("ssl_cert_file={}", cert.display()))
        .arg("-c")
        .arg(format!("ssl_key_file={}", key.display()));
    let server = Process::start(dir, &mut command, port);
    let deadline = Instant::now() + Duration::from_secs(10);
    loop {
        let status = Command::new(bin.join("pg_isready"))
            .args(["-q", "-h", HOST, "-p", &port.to_string(), "-U", "mqtt"])
            .status()
            .unwrap();
        if status.success() {
            break;
        }
        assert!(
            Instant::now() < deadline,
            "PostgreSQL is not ready: {}",
            server.log()
        );
        thread::sleep(Duration::from_millis(30));
    }
    run(
        Command::new(bin.join("psql")).args([
            "-h",
            HOST,
            "-p",
            &port.to_string(),
            "-U",
            "mqtt",
            "-d",
            "postgres",
            "-v",
            "ON_ERROR_STOP=1",
        ]),
        Some(&sql_seed()),
    );
    (server, port)
}

